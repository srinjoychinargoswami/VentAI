Vent AI uses an offline AI model (Gemma 4 E2B) that runs entirely on your device:
* The AI model is downloaded once from Hugging Face (about 2.6 GB) on first launch. Like any website, Hugging Face sees your device's IP address during that download. After download, the app works completely offline
